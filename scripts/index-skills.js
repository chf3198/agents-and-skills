#!/usr/bin/env node
/**
 * index-skills.js — Generate skills/INDEX.md from all SKILL.md files
 *
 * Scans skills/ directories, reads each SKILL.md frontmatter, and writes
 * a sorted markdown table to skills/INDEX.md.
 */

import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml } from 'yaml';

const __dirname = fileURLToPath(new URL('.', import.meta.url));
const SKILLS_DIR = join(__dirname, '../skills');
const INDEX_PATH = join(SKILLS_DIR, 'INDEX.md');

const FRONTMATTER_RE = /^---\n([\s\S]+?)\n---/;

const skillDirs = readdirSync(SKILLS_DIR)
  .filter(d => {
    const full = join(SKILLS_DIR, d);
    return statSync(full).isDirectory() && d !== '__pycache__';
  })
  .sort();

const rows = [];
for (const dir of skillDirs) {
  const skillPath = join(SKILLS_DIR, dir, 'SKILL.md');
  let content;
  try { content = readFileSync(skillPath, 'utf8'); } catch { continue; }
  const fmMatch = content.match(FRONTMATTER_RE);
  if (!fmMatch) continue;
  let fm;
  try { fm = parseYaml(fmMatch[1]) ?? {}; } catch { continue; }
  const desc = (fm.description || '').replace(/\n/g, ' ').replace(/\s+/g, ' ').trim();
  rows.push({ name: fm.name || dir, dir, desc, license: fm.license || '' });
}

const table = [
  '| Skill | Description | License |',
  '|---|---|---|',
  ...rows.map(r => `| [\`${r.name}\`](${r.dir}/SKILL.md) | ${r.desc} | ${r.license} |`),
].join('\n');

const content = `# Skills Index

> Auto-generated by \`npm run index:skills\`. Do not edit manually.
> Last updated: ${new Date().toISOString()}

${table}

## Installing a Skill

### Claude Code
\`\`\`bash
# Register this repo as a skill marketplace
/plugin marketplace add <your-github-username>/<repo-name>

# Or copy directly
cp -r skills/<skill-name> ~/.claude/skills/
\`\`\`

### Copilot
Skills in this repo are referenced via \`.github/copilot-instructions.md\` and
\`.github/instructions/*.instructions.md\`. To use them in a different repo,
copy the relevant \`*.instructions.md\` files into that repo's \`.github/instructions/\`.

### Generic (any AGENTS.md-compatible agent)
\`\`\`bash
cp -r skills/<skill-name> ~/.agents/skills/
\`\`\`
`;

writeFileSync(INDEX_PATH, content);
console.log(`Generated ${INDEX_PATH} with ${rows.length} skill(s).`);
